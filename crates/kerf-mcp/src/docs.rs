//! Deterministic project-local documentation generated from live Kerf APIs.
//!
//! The generated bundle is deliberately an output of the runtime and MCP
//! adapters. It is never read back as project state and never replaces the
//! user-owned `.kerf/docs/conventions.md` file.

use super::{CutMcpRouter, ToolDefinition};
use kerf_lang::Clock;
use kerf_model::{Catalog, Project};
use kerf_runtime::{RequestEnvelope, RuntimeError};
use kerf_skills::Skill;
use serde_json::{json, Value};
use std::fmt::{self, Write as FmtWrite};
use std::fs;
use std::io::{self, Write as IoWrite};
use std::path::{Path, PathBuf};

/// Version of the generated documentation envelope and markdown contract.
pub const GENERATED_DOCS_SCHEMA_VERSION: u8 = 1;
/// Relative directory containing machine-owned documentation files.
pub const GENERATED_DOCS_RELATIVE_DIR: &str = ".kerf/docs/generated";
/// User-facing command that refreshes the generated bundle.
pub const REGENERATION_COMMAND: &str = "kerf --generate-docs";
/// MCP protocol revision advertised by the native server.
pub const MCP_PROTOCOL_VERSION: &str = "2024-11-05";

const GENERATED_MARKDOWN_HEADER: &str = "<!-- GENERATED BY KERF. DO NOT EDIT. -->\n";
const AGENTS_POINTER_MARKER: &str = "<!-- KERF GENERATED DOCS POINTER -->";
const AGENTS_POINTER: &str = "<!-- KERF GENERATED DOCS POINTER -->\nRead the project-local Kerf contract in `.kerf/docs/generated/protocol.md`, `.kerf/docs/generated/tools.json`, `.kerf/docs/generated/skills.md`, and `.kerf/docs/generated/project-summary.md`. These files are generated; keep editorial guidance in `.kerf/docs/conventions.md`.\n<!-- END KERF GENERATED DOCS POINTER -->\n";

/// Paths written by one successful documentation generation.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedDocs {
    pub directory: PathBuf,
    pub files: Vec<PathBuf>,
    pub revision: u64,
}

/// Failure while reading the authoritative snapshot or writing generated docs.
#[derive(Debug)]
pub enum DocsError {
    Runtime(RuntimeError),
    InvalidProject(String),
    Serialization(serde_json::Error),
    Io(io::Error),
    ProtectedPath(PathBuf),
}

impl fmt::Display for DocsError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Runtime(error) => write!(formatter, "{}: {}", error.code, error.message),
            Self::InvalidProject(message) => write!(formatter, "invalid project: {message}"),
            Self::Serialization(error) => write!(formatter, "serialize generated docs: {error}"),
            Self::Io(error) => write!(formatter, "write generated docs: {error}"),
            Self::ProtectedPath(path) => write!(
                formatter,
                "refusing to overwrite non-generated file: {}",
                path.display()
            ),
        }
    }
}

impl std::error::Error for DocsError {}

impl From<RuntimeError> for DocsError {
    fn from(error: RuntimeError) -> Self {
        Self::Runtime(error)
    }
}

impl From<serde_json::Error> for DocsError {
    fn from(error: serde_json::Error) -> Self {
        Self::Serialization(error)
    }
}

impl From<io::Error> for DocsError {
    fn from(error: io::Error) -> Self {
        Self::Io(error)
    }
}

/// Generate the four project-local agent documentation files.
pub fn generate_agent_docs(router: &CutMcpRouter) -> Result<GeneratedDocs, DocsError> {
    let (revision, document) = router.runtime().get_document(false)?;
    let project = kerf_lang::parse_document(&document, Catalog::builtin())
        .map(|document| document.project)
        .map_err(|errors| {
            DocsError::InvalidProject(
                errors
                    .iter()
                    .map(ToString::to_string)
                    .collect::<Vec<_>>()
                    .join("; "),
            )
        })?;
    let metadata = metadata(revision);
    let tools = router.list_tools();
    let directory = router
        .runtime()
        .directory()
        .join(GENERATED_DOCS_RELATIVE_DIR);
    fs::create_dir_all(&directory)?;

    let contents = [
        ("protocol.md", protocol_markdown(&metadata, &tools)?),
        ("tools.json", tools_json(&metadata, &tools)?),
        ("skills.md", skills_markdown(&metadata, router.skills())),
        (
            "project-summary.md",
            project_summary_markdown(&metadata, &project),
        ),
    ];
    let mut files = Vec::with_capacity(contents.len());
    for (name, content) in contents {
        let path = directory.join(name);
        write_generated(&path, &content)?;
        files.push(path);
    }
    Ok(GeneratedDocs {
        directory,
        files,
        revision,
    })
}

/// Add a project-local generated-docs pointer without replacing user content.
///
/// This function is intentionally separate from [`generate_agent_docs`]. The
/// normal generator never touches a root `AGENTS.md`; callers must explicitly
/// opt into this append-only helper.
pub fn add_agents_pointer(directory: &Path) -> Result<PathBuf, DocsError> {
    let path = directory.join("AGENTS.md");
    if fs::read_to_string(&path)
        .map(|content| content.contains(AGENTS_POINTER_MARKER))
        .unwrap_or(false)
    {
        return Ok(path);
    }

    let exists = path.exists();
    let mut file = fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&path)?;
    if exists && fs::metadata(&path)?.len() > 0 {
        file.write_all(b"\n\n")?;
    }
    file.write_all(AGENTS_POINTER.as_bytes())?;
    Ok(path)
}

fn metadata(revision: u64) -> Value {
    json!({
        "_generated": {
            "owner": "kerf",
            "doNotEdit": true,
            "generator": "kerf-mcp",
            "generatorVersion": env!("CARGO_PKG_VERSION")
        },
        "schemaVersion": GENERATED_DOCS_SCHEMA_VERSION,
        "generatedBy": "kerf-mcp",
        "generatorVersion": env!("CARGO_PKG_VERSION"),
        "regenerationCommand": REGENERATION_COMMAND,
        "deterministic": true,
        "mcpProtocolVersion": MCP_PROTOCOL_VERSION,
        "kerfdProtocolVersion": RequestEnvelope::PROTOCOL_VERSION,
        "projectRevision": revision,
    })
}

fn protocol_markdown(metadata: &Value, tools: &[ToolDefinition]) -> Result<String, DocsError> {
    let mut output = markdown_header();
    output.push_str("# Kerf agent protocol\n\n");
    write_metadata_markdown(&mut output, metadata);
    output.push_str(
        "All project state is owned by `kerfd`. Agents read the annotated `.kerf` document with `look`, change it with `edit` scripts, and render with `render`. Every edit is a proposal until a person accepts it. The resource `kerf://reference` holds the edit language and every property, effect, transition, and generator. Generated files are documentation only.\n\n",
    );
    output.push_str("## Tools\n\n");
    for tool in tools {
        let _ = writeln!(output, "### `{}`\n", markdown_inline(&tool.name));
        let _ = writeln!(output, "{}\n", markdown_text(&tool.description));
        let annotations = serde_json::to_string(&tool.annotations)?;
        let _ = writeln!(output, "- Annotations: `{annotations}`\n");
        output.push_str("```json\n");
        output.push_str(&serde_json::to_string_pretty(&tool.input_schema)?);
        output.push_str("\n```\n\n");
    }
    Ok(output)
}

fn tools_json(metadata: &Value, tools: &[ToolDefinition]) -> Result<String, DocsError> {
    let mut document = metadata
        .as_object()
        .cloned()
        .ok_or_else(|| DocsError::InvalidProject("generated metadata is not an object".into()))?;
    document.insert("tools".into(), serde_json::to_value(tools)?);
    let mut output = serde_json::to_string_pretty(&Value::Object(document))?;
    output.push('\n');
    Ok(output)
}

fn skills_markdown(metadata: &Value, skills: &[Skill]) -> String {
    let mut output = markdown_header();
    output.push_str("# Kerf skills\n\n");
    write_metadata_markdown(&mut output, metadata);
    output.push_str(
        "Skills carry editorial guidance and are part of the agent's instructions. Project skills override user skills, which override bundled skills.\n\n",
    );
    output.push_str("## Installed skills\n\n");
    if skills.is_empty() {
        output.push_str("No skills are installed.\n");
    } else {
        for skill in skills {
            let _ = writeln!(
                output,
                "- `{}`: {}",
                markdown_inline(&skill.name),
                markdown_text(&skill.description)
            );
        }
    }
    output
}

fn project_summary_markdown(metadata: &Value, project: &Project) -> String {
    let mut output = markdown_header();
    output.push_str("# Kerf project summary\n\n");
    write_metadata_markdown(&mut output, metadata);
    let _ = writeln!(output, "- Project: **{}**", markdown_text(&project.name));
    let _ = writeln!(output, "- Media: `{}`", project.media.len());
    let _ = writeln!(output, "- Sequences: `{}`", project.sequences.len());
    output.push_str("- Document: `project.kerf`; agents read it annotated with `look`\n");
    output.push_str("- User-owned guidance: `.kerf/docs/conventions.md` (preserved)\n\n");

    output.push_str("## Sequences\n\n");
    if project.sequences.is_empty() {
        output.push_str("No sequences.\n\n");
    } else {
        output.push_str(
            "| ID | Name | Rate | Size | Duration | Tracks | Clips |\n| --- | --- | ---: | ---: | ---: | ---: | ---: |\n",
        );
        for sequence in &project.sequences {
            let clock = Clock::of_sequence(sequence);
            let _ = writeln!(
                output,
                "| `{}` | {} | `{}` | `{}×{}` | `{}` | `{}` | `{}` |",
                markdown_inline(sequence.id.as_str()),
                markdown_table_text(&sequence.name),
                sequence.rate,
                sequence.width,
                sequence.height,
                clock.print_duration(sequence.duration()),
                sequence.tracks.len(),
                sequence
                    .tracks
                    .iter()
                    .map(|track| track.clips.len())
                    .sum::<usize>()
            );
        }
        output.push('\n');
    }

    output.push_str("## Media\n\n");
    if project.media.is_empty() {
        output.push_str("No media.\n");
    } else {
        output.push_str("| ID | Path | Duration |\n| --- | --- | ---: |\n");
        for media in &project.media {
            let _ = writeln!(
                output,
                "| `{}` | {} | `{:.3}s` |",
                markdown_inline(media.id.as_str()),
                markdown_table_text(&media.path),
                media.duration.seconds()
            );
        }
    }
    output
}

fn markdown_header() -> String {
    GENERATED_MARKDOWN_HEADER.into()
}

fn write_metadata_markdown(output: &mut String, metadata: &Value) {
    let value = |key: &str| {
        metadata
            .get(key)
            .map(display_json_value)
            .unwrap_or_default()
    };
    let _ = writeln!(output, "- App version: `{}`", value("generatorVersion"));
    let _ = writeln!(output, "- MCP protocol: `{}`", value("mcpProtocolVersion"));
    let _ = writeln!(
        output,
        "- kerfd protocol: `{}`",
        value("kerfdProtocolVersion")
    );
    let _ = writeln!(output, "- Project revision: `{}`", value("projectRevision"));
    let _ = writeln!(output, "- Regeneration: `{}`", value("regenerationCommand"));
    let _ = writeln!(output, "- Deterministic: `{}`\n", value("deterministic"));
}

fn display_json_value(value: &Value) -> String {
    match value {
        Value::String(value) => value.clone(),
        value => value.to_string(),
    }
}

fn markdown_inline(value: &str) -> String {
    value.replace('`', "'").replace(['\n', '\r'], " ")
}

fn markdown_text(value: &str) -> String {
    value.replace(['\n', '\r'], " ").replace('|', "\\|")
}

fn markdown_table_text(value: &str) -> String {
    markdown_text(&markdown_inline(value))
}

fn write_generated(path: &Path, content: &str) -> Result<(), DocsError> {
    if let Ok(existing) = fs::read_to_string(path) {
        if existing == content {
            return Ok(());
        }
        if !is_generated_content(path, &existing) {
            return Err(DocsError::ProtectedPath(path.to_path_buf()));
        }
    }

    let file_name = path
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("generated");
    let temporary = path.with_file_name(format!(".{file_name}.{}.tmp", std::process::id()));
    fs::write(&temporary, content)?;
    if let Err(error) = fs::rename(&temporary, path) {
        let _ = fs::remove_file(&temporary);
        return Err(DocsError::Io(error));
    }
    Ok(())
}

fn is_generated_content(path: &Path, content: &str) -> bool {
    if path.extension().and_then(|extension| extension.to_str()) == Some("json") {
        return serde_json::from_str::<Value>(content)
            .ok()
            .and_then(|value| value.get("_generated").cloned())
            .and_then(|value| value.get("owner").cloned())
            .and_then(|value| value.as_str().map(str::to_owned))
            .as_deref()
            == Some("kerf");
    }
    content.starts_with(GENERATED_MARKDOWN_HEADER)
}

#[cfg(test)]
mod tests {
    use super::{
        add_agents_pointer, is_generated_content, write_generated, DocsError,
        GENERATED_DOCS_RELATIVE_DIR,
    };
    use std::fs;
    use tempfile::TempDir;

    #[test]
    fn generated_writer_is_deterministic_and_preserves_user_guidance() {
        let root = TempDir::new().expect("project dir");
        let user_docs = root.path().join(".kerf/docs");
        fs::create_dir_all(&user_docs).expect("docs dir");
        fs::write(user_docs.join("conventions.md"), "# Keep this").expect("conventions");
        fs::write(root.path().join("AGENTS.md"), "# User instructions").expect("agents");

        let generated_dir = root.path().join(GENERATED_DOCS_RELATIVE_DIR);
        fs::create_dir_all(&generated_dir).expect("generated dir");
        let path = generated_dir.join("protocol.md");
        let content = "<!-- GENERATED BY KERF. DO NOT EDIT. -->\n# Protocol\n";
        write_generated(&path, content).expect("generated docs");
        let first = fs::read(&path).expect("generated file");
        write_generated(&path, content).expect("regenerated docs");
        let regenerated = fs::read(&path).expect("generated file");

        assert_eq!(first, regenerated);
        assert_eq!(
            fs::read_to_string(user_docs.join("conventions.md")).unwrap(),
            "# Keep this"
        );
        assert_eq!(
            fs::read_to_string(root.path().join("AGENTS.md")).unwrap(),
            "# User instructions"
        );
        assert!(is_generated_content(&path, content));
    }

    #[test]
    fn generated_writer_does_not_overwrite_an_unmarked_path() {
        let root = TempDir::new().expect("project dir");
        let generated_dir = root.path().join(GENERATED_DOCS_RELATIVE_DIR);
        fs::create_dir_all(&generated_dir).expect("generated dir");
        fs::write(generated_dir.join("protocol.md"), "user content").expect("user file");

        let error = write_generated(
            &generated_dir.join("protocol.md"),
            "<!-- GENERATED BY KERF. DO NOT EDIT. -->\n# New protocol\n",
        )
        .expect_err("protected path");
        assert!(matches!(error, DocsError::ProtectedPath(path) if path.ends_with("protocol.md")));
        assert_eq!(
            fs::read_to_string(generated_dir.join("protocol.md")).unwrap(),
            "user content"
        );
    }

    #[test]
    fn agents_pointer_is_explicit_and_append_only() {
        let root = TempDir::new().expect("project dir");
        let agents = root.path().join("AGENTS.md");
        fs::write(&agents, "# User instructions\n").expect("agents file");

        add_agents_pointer(root.path()).expect("add pointer");
        let first = fs::read_to_string(&agents).expect("agents file");
        add_agents_pointer(root.path()).expect("keep pointer idempotent");
        assert_eq!(first, fs::read_to_string(&agents).expect("agents file"));
        assert!(first.starts_with("# User instructions"));
        assert!(first.contains(".kerf/docs/generated/protocol.md"));
    }
}
